// Combines every migration into supabase/setup.sql: one script that sets up a brand-new
// Supabase project in a single paste into the SQL Editor.
//
//   node scripts/build-setup-sql.mjs
//
// Existing projects keep applying the numbered migrations one at a time; this is only for
// starting fresh. Regenerate it whenever a migration is added.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((name) => name.endsWith(".sql")).sort();

const parts = [
  "-- Sets up a NEW, EMPTY Supabase project for Siza in one go.",
  "-- Generated by scripts/build-setup-sql.mjs from supabase/migrations/. Don't edit by hand.",
  "-- Paste the whole file into the SQL Editor and run it once. It runs as one transaction:",
  "-- if anything fails, nothing is changed.",
  "",
  ...files.flatMap((name) => [`-- ════════ ${name} ════════`, readFileSync(join(dir, name), "utf8").trim(), ""]),
];
writeFileSync(join(root, "supabase", "setup.sql"), parts.join("\n"));
console.log(`supabase/setup.sql: ${files.length} migrations, ${(parts.join("\n").length / 1024).toFixed(0)} KB`);
